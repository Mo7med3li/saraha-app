/**
 * Builds a frozen OpenAPI document from controller JSDoc.
 * Run locally (or in CI) so Vercel serverless does not need to glob .ts files.
 *
 *   node scripts/generate-openapi.cjs
 */
const fs = require("node:fs");
const path = require("node:path");
const swaggerJsdoc = require("swagger-jsdoc");

const root = path.join(__dirname, "..");
const outFile = path.join(
  root,
  "src/lib/utils/swagger/openapi.generated.ts",
);

const apis = [
  path.join(root, "src/modules/auth/controller/auth.controller.ts"),
  path.join(root, "src/modules/users/controller/users.controller.ts"),
  path.join(root, "src/modules/messages/controller/messages.controller.ts"),
];

for (const file of apis) {
  if (!fs.existsSync(file)) {
    console.error("Missing controller for OpenAPI scan:", file);
    process.exit(1);
  }
}

// Minimal definition — runtime getSwaggerSpec overwrites info/servers/components
const spec = swaggerJsdoc({
  definition: {
    openapi: "3.0.3",
    info: {
      title: "Saraha API",
      version: "1.0.0",
    },
  },
  apis,
});

const pathCount = Object.keys(spec.paths || {}).length;
if (pathCount === 0) {
  console.error("OpenAPI generation produced 0 paths — aborting.");
  process.exit(1);
}

const banner = `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-openapi.cjs — do not edit by hand.
 * Regenerate: npm run swagger:generate
 */
`;

const body = `${banner}export const openapiGenerated = ${JSON.stringify(spec, null, 2)} as const;
`;

fs.writeFileSync(outFile, body, "utf8");
console.log(
  `Wrote ${pathCount} paths → ${path.relative(root, outFile)}`,
);
